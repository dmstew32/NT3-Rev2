"""Copy C function definitions (unchanged) from source files into one file.

usage: extract_funcs.py OUT.c SRC.c:func1,func2 [SRC2.c:func3 ...]

Used by the button test to compile the feature functions the buttons call
(toggle_50_percent_mode(), ...) without compiling the rest of their modules.
"""
import re
import sys


def extract(src, name):
    m = re.search(r'^(?:static\s+)?void\s+' + name + r'\s*\([^;{]*\)\s*\n\{', src, re.M)
    if not m:
        sys.exit('extract_funcs.py: %s not found' % name)
    depth = 0
    i = m.end() - 1
    while True:
        if src[i] == '{':
            depth += 1
        elif src[i] == '}':
            depth -= 1
            if depth == 0:
                return src[m.start():i + 1] + '\n'
        i += 1


out = ['// GENERATED by extract_funcs.py - do not edit\n', '#include "hal_buttons.h"   // BUTTON_PRINT\n']
for spec in sys.argv[2:]:
    path, names = spec.rsplit(':', 1)
    src = open(path, 'rb').read().decode('latin-1').replace('\r\n', '\n')
    funcs = [extract(src, n) for n in names.split(',')]
    # declare static functions first so definition order doesn't matter
    for f in funcs:
        head = f.split('\n', 1)[0]
        if head.startswith('static '):
            out.append(head + ';\n')
    out.append('\n// from %s\n' % path)
    out += [f + '\n' for f in funcs]
open(sys.argv[1], 'w', newline='\n').write(''.join(out))
